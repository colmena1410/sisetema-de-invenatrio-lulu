    private void CREARActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CREARActionPerformed
       // Leemos los datos de las cajas de texto de tu formulario
    String numeroId = ID1.getText().trim(); // Cédula o ID (Primary Key)
    String nombre = NOMBRE1.getText().trim();
    String celular = CELULAR1.getText().trim();
    String direccion = DIRECCION.getText().trim();
    String correo = CORREO1.getText().trim();

    // Validamos campos obligatorios
    if (numeroId.isEmpty() || nombre.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor complete al menos la Cédula/ID y el Nombre.");
        return;
    }

    // Consulta SQL para insertar en la tabla clientes
    String sql = "INSERT INTO clientes (numero_id, nombre, celular, direccion, correo) VALUES (?, ?, ?, ?, ?)";

    try (java.sql.Connection conn = Conexion.conectar();
         java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {
        
        pstmt.setString(1, numeroId);
        pstmt.setString(2, nombre);
        pstmt.setString(3, celular);
        pstmt.setString(4, direccion);
        pstmt.setString(5, correo);
        pstmt.executeUpdate();

        javax.swing.JOptionPane.showMessageDialog(this, "¡Cliente registrado con éxito en la base de datos!");
        
        // Limpiar cajas de texto
        ID1.setText("");
        NOMBRE1.setText("");
        CELULAR1.setText("");
        DIRECCION.setText("");
        CORREO1.setText("");
        
        // Si es una ventana independiente, ciérrala al terminar:
        this.dispose();
        
    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar (la Cédula/ID ya podría existir): " + e.getMessage());
    }
    }//GEN-LAST:event_CREARActionPerformed

    private void ELIMINARActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ELIMINARActionPerformed
      int filaSeleccionada = jTable1.getSelectedRow();

if (filaSeleccionada == -1) {
    javax.swing.JOptionPane.showMessageDialog(this, "Por favor seleccione un cliente de la tabla para eliminar.", "Advertencia", javax.swing.JOptionPane.WARNING_MESSAGE);
    return;
}

int confirmar = javax.swing.JOptionPane.showConfirmDialog(this, "¿Está seguro de eliminar este cliente?", "Confirmar eliminación", javax.swing.JOptionPane.YES_NO_OPTION);

if (confirmar == javax.swing.JOptionPane.YES_OPTION) {
    // 1. Obtenemos el número_id del cliente (asumiendo que está en la columna 1, ajústalo a 0 si tu ID está en la primera columna)
    Object idCliente = modeloClientesGlobal.getValueAt(filaSeleccionada, 1);

    // 2. Ejecutamos el DELETE en la base de datos
    try (java.sql.Connection conn = Conexion.conectar();
         java.sql.PreparedStatement pstmt = conn.prepareStatement("DELETE FROM clientes WHERE numero_id = ?")) {
        
        pstmt.setObject(1, idCliente);
        pstmt.executeUpdate();

        // 3. Quitamos la fila de la interfaz visual
        modeloClientesGlobal.removeRow(filaSeleccionada);
        javax.swing.JOptionPane.showMessageDialog(this, "Cliente eliminado correctamente de la base de datos.", "Éxito", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        
    } catch (java.sql.SQLException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error al eliminar en la base de datos: " + ex.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
}  
    }//GEN-LAST:event_ELIMINARActionPerformed

    private void EDITARActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EDITARActionPerformed
       int filaSeleccionada = jTable1.getSelectedRow();

if (filaSeleccionada == -1) {
    javax.swing.JOptionPane.showMessageDialog(this, "Por favor seleccione un cliente de la tabla para editar.", "Advertencia", javax.swing.JOptionPane.WARNING_MESSAGE);
    return;
}

// Guardamos el ID original que sirve para buscar el registro en la base de datos
Object idOriginal = modeloClientesGlobal.getValueAt(filaSeleccionada, 1);

String actualNombre = modeloClientesGlobal.getValueAt(filaSeleccionada, 0).toString();
String actualId = modeloClientesGlobal.getValueAt(filaSeleccionada, 1).toString();
String actualCelular = modeloClientesGlobal.getValueAt(filaSeleccionada, 2).toString();
String actualDireccion = modeloClientesGlobal.getValueAt(filaSeleccionada, 3).toString();
String actualCorreo = modeloClientesGlobal.getValueAt(filaSeleccionada, 4).toString();

String nuevoNombre = javax.swing.JOptionPane.showInputDialog(this, "Edite el Nombre:", actualNombre);
if (nuevoNombre == null) return;

String nuevoId = javax.swing.JOptionPane.showInputDialog(this, "Edite el Número ID:", actualId);
if (nuevoId == null) return;

String nuevoCelular = javax.swing.JOptionPane.showInputDialog(this, "Edite el Celular:", actualCelular);
if (nuevoCelular == null) return;

String nuevaDireccion = javax.swing.JOptionPane.showInputDialog(this, "Edite la Dirección:", actualDireccion);
if (nuevaDireccion == null) return;

String nuevoCorreo = javax.swing.JOptionPane.showInputDialog(this, "Edite el Correo:", actualCorreo);
if (nuevoCorreo == null) return;

// Ejecutamos el UPDATE en la base de datos SQLite
try (java.sql.Connection conn = Conexion.conectar();
     java.sql.PreparedStatement pstmt = conn.prepareStatement("UPDATE clientes SET numero_id = ?, nombre = ?, celular = ?, direccion = ?, correo = ? WHERE numero_id = ?")) {
    
    pstmt.setString(1, nuevoId.trim());
    pstmt.setString(2, nuevoNombre.trim());
    pstmt.setString(3, nuevoCelular.trim());
    pstmt.setString(4, nuevaDireccion.trim());
    pstmt.setString(5, nuevoCorreo.trim());
    pstmt.setObject(6, idOriginal); // Usamos el ID original para ubicar el registro en la BD
    pstmt.executeUpdate();

    // Actualizamos el modelo global visual
    modeloClientesGlobal.setValueAt(nuevoNombre.trim(), filaSeleccionada, 0);
    modeloClientesGlobal.setValueAt(nuevoId.trim(), filaSeleccionada, 1);
    modeloClientesGlobal.setValueAt(nuevoCelular.trim(), filaSeleccionada, 2);
    modeloClientesGlobal.setValueAt(nuevaDireccion.trim(), filaSeleccionada, 3);
    modeloClientesGlobal.setValueAt(nuevoCorreo.trim(), filaSeleccionada, 4);

    javax.swing.JOptionPane.showMessageDialog(this, "¡Cliente actualizado correctamente en la base de datos!", "Éxito", javax.swing.JOptionPane.INFORMATION_MESSAGE);

} catch (java.sql.SQLException ex) {
    javax.swing.JOptionPane.showMessageDialog(this, "Error al actualizar en la base de datos (el ID podría estar repetido): " + ex.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_EDITARActionPerformed

