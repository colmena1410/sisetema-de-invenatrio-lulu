public void cargarProveedoresDesdeBD() {
    modeloProveedoresGlobal.setRowCount(0);
    String sql = "SELECT * FROM proveedores";
    try (java.sql.Connection conn = Conexion.conectar();
         java.sql.Statement stmt = conn.createStatement();
         java.sql.ResultSet rs = stmt.executeQuery(sql)) {
        while (rs.next()) {
            modeloProveedoresGlobal.addRow(new Object[]{
                rs.getString("nombre"),
                rs.getString("id"),
                rs.getString("direccion"),
                rs.getString("correo")
            });
        }
    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error al cargar proveedores: " + e.getMessage());
    }
    }

