    // Método que se ejecuta cuando sehace clic en el botón de Guardar/Registrar usuario
    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {                                         
        String usuario = txtUsuario.getText().trim(); // Asegúrate de que tu caja de texto se llame txtUsuario
        String password = new String(txtContraseña.getPassword()).trim(); // O txtContrasena.getText() si es JTextField normal
        
        
        Object rolObj = cmbRol.getSelectedItem(); 
        if (usuario.isEmpty() || password.isEmpty() || rolObj == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor complete todos los campos.");
            return;
        }

        String rol = rolObj.toString().trim().toLowerCase();

        // Inserción en la base de datos SQLite
        String sql = "INSERT INTO usuarios (usuario, contrasena, rol) VALUES (?, ?, ?)";

        try (java.sql.Connection conn = Conexion.conectar();
             java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {
            
            pstmt.setString(1, usuario);
            pstmt.setString(2, password);
            pstmt.setString(3, rol);
            pstmt.executeUpdate();

            javax.swing.JOptionPane.showMessageDialog(this, "¡Usuario registrado con éxito en la base de datos!");
            
            // Limpiar campos después de guardar
            txtUsuario.setText("");
            txtContraseña.setText("");
            
            // Cierra la ventana de registro al terminar
            this.dispose();
            
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar (el usuario ya podría registrarse o existe): " + e.getMessage());
        }
    }
