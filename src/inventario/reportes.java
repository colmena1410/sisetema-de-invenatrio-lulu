    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
DefaultTableModel modelo = ProductosIngresados.modeloTablaGlobal;
if (modelo == null || modelo.getRowCount() == 0) {
    JOptionPane.showMessageDialog(this, "No hay productos en el inventario para exportar.");
    return;
}

JFileChooser selector = new JFileChooser();
selector.setDialogTitle("Guardar Reporte de Inventario");
selector.setSelectedFile(new File("Reporte_Inventario_LuluBeauty.xlsx"));

if (selector.showSaveDialog(this) == JFileChooser.APPROVE_OPTION) {
    File archivo = selector.getSelectedFile();
    if (!archivo.getName().toLowerCase().endsWith(".xlsx")) {
        archivo = new File(archivo.getParentFile(), archivo.getName() + ".xlsx");
    }

    try (FileOutputStream os = new FileOutputStream(archivo);
         Workbook wb = new Workbook(os, "LuluBeauty", "1.0")) {
        
        Worksheet ws = wb.newWorksheet("Inventario");
        
        // Encabezados limpios para el Excel
        String[] encabezados = {"Producto", "Proveedor", "Precio", "Costo", "Stock"};
        for (int col = 0; col < encabezados.length; col++) {
            ws.value(0, col, encabezados[col]);
            ws.style(0, col).bold().fillColor("2C3E50").fontColor("FFFFFF").set();
        }
        
        for (int i = 0; i < modelo.getRowCount(); i++) {
            int rowIdx = i + 1;
            
            // ⚠️ Ajuste de índices por el ID inicial de la tabla:
            String producto  = modelo.getValueAt(i, 1) != null ? modelo.getValueAt(i, 1).toString() : "";
            String proveedor = modelo.getValueAt(i, 2) != null ? modelo.getValueAt(i, 2).toString() : "";
            
            String precioStr = modelo.getValueAt(i, 3) != null ? modelo.getValueAt(i, 3).toString().replaceAll("[^0-9.]", "").trim() : "0";
            String costoStr  = modelo.getValueAt(i, 4) != null ? modelo.getValueAt(i, 4).toString().replaceAll("[^0-9.]", "").trim() : "0";
            String stockStr  = modelo.getValueAt(i, 5) != null ? modelo.getValueAt(i, 5).toString().replaceAll("[^0-9]", "").trim() : "0";
            
            // Convertir a valores numéricos reales
            double precio = precioStr.isEmpty() ? 0.0 : Double.parseDouble(precioStr);
            double costo  = costoStr.isEmpty() ? 0.0 : Double.parseDouble(costoStr);
            int stock     = stockStr.isEmpty() ? 0 : Integer.parseInt(stockStr);
            
            // Escribir en orden perfecto en el Excel (omitiendo el ID de la tabla)
            ws.value(rowIdx, 0, producto);  // Columna A: Producto ("perra")
            ws.value(rowIdx, 1, proveedor); // Columna B: Proveedor ("as")
            ws.value(rowIdx, 2, precio);    // Columna C: Precio (ej. 20000.0)
            ws.value(rowIdx, 3, costo);     // Columna D: Costo (ej. 155.0)
            ws.value(rowIdx, 4, stock);     // Columna E: Stock (ej. 15)
        }
        
        JOptionPane.showMessageDialog(this, "¡Reporte de Inventario exportado con éxito!");
    } catch (Exception ex) {
        if (archivo.exists()) {
            archivo.delete();
        }
        JOptionPane.showMessageDialog(this, "Error al exportar: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
}
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
  DefaultTableModel modelo = ProductosIngresados.modeloTablaGlobal;
    if (modelo == null || modelo.getRowCount() == 0) {
        JOptionPane.showMessageDialog(this, "No hay productos para calcular costos.");
        return;
    }

    JFileChooser selector = new JFileChooser();
    selector.setDialogTitle("Guardar Reporte de Costos");
    selector.setSelectedFile(new File("Reporte_Costos_LuluBeauty.xlsx"));

    if (selector.showSaveDialog(this) == JFileChooser.APPROVE_OPTION) {
        File archivo = selector.getSelectedFile();
        if (!archivo.getName().toLowerCase().endsWith(".xlsx")) {
            archivo = new File(archivo.getParentFile(), archivo.getName() + ".xlsx");
        }

        try (FileOutputStream os = new FileOutputStream(archivo);
             Workbook wb = new Workbook(os, "LuluBeauty", "1.0")) {
            
            Worksheet ws = wb.newWorksheet("Costos Totales");
            
            String[] encabezados = {"Producto", "Costo Unitario", "Stock", "Costo Total"};
            for (int col = 0; col < encabezados.length; col++) {
                ws.value(0, col, encabezados[col]);
                ws.style(0, col).bold().fillColor("2C3E50").fontColor("FFFFFF").set();
            }
            
            double costoGlobal = 0;
            int rowIdx = 1;
            for (int i = 0; i < modelo.getRowCount(); i++) {
                rowIdx = i + 1;
                
                // 1. Nombre del producto en columna 1
                String nombre = modelo.getValueAt(i, 1) != null ? modelo.getValueAt(i, 1).toString() : "";
                
                // 2. Costo Unitario en columna 4 (la columna 3 es el Precio)
                String costoStr = modelo.getValueAt(i, 4) != null ? modelo.getValueAt(i, 4).toString().replaceAll("[^0-9.]", "").trim() : "0";
                
                // 3. Stock en columna 5
                String stockStr = modelo.getValueAt(i, 5) != null ? modelo.getValueAt(i, 5).toString().replaceAll("[^0-9]", "").trim() : "0";
                
                double costo = costoStr.isEmpty() ? 0.0 : Double.parseDouble(costoStr);
                int stock = stockStr.isEmpty() ? 0 : Integer.parseInt(stockStr);
                
                double totalProd = costo * stock;
                costoGlobal += totalProd;
                
                ws.value(rowIdx, 0, nombre);
                ws.value(rowIdx, 1, costo);
                ws.value(rowIdx, 2, stock);
                ws.value(rowIdx, 3, totalProd);
            }
            
            // Fila de Total Invertido
            rowIdx++;
            ws.value(rowIdx, 2, "TOTAL INVERTIDO:");
            ws.style(rowIdx, 2).bold().set();
            ws.value(rowIdx, 3, costoGlobal);
            ws.style(rowIdx, 3).bold().set();
            
            JOptionPane.showMessageDialog(this, "¡Reporte de Costos exportado con éxito!");
        } catch (Exception ex) {
            if (archivo.exists()) {
                archivo.delete();
            }
            JOptionPane.showMessageDialog(this, "Error al exportar: " + ex.getMessage());
        }
    }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
     DefaultTableModel modeloVentas = ventas.modeloTablaGlobal;
    if (modeloVentas == null || modeloVentas.getRowCount() == 0) {
        JOptionPane.showMessageDialog(this, "No hay registros de ventas para calcular ganancias.");
        return;
    }

    JFileChooser selector = new JFileChooser();
    selector.setDialogTitle("Guardar Reporte de Ganancias");
    selector.setSelectedFile(new File("Reporte_Ganancias_LuluBeauty.xlsx"));

    if (selector.showSaveDialog(this) == JFileChooser.APPROVE_OPTION) {
        File archivo = selector.getSelectedFile();
        if (!archivo.getName().toLowerCase().endsWith(".xlsx")) {
            archivo = new File(archivo.getParentFile(), archivo.getName() + ".xlsx");
        }

        try (FileOutputStream os = new FileOutputStream(archivo);
             Workbook wb = new Workbook(os, "LuluBeauty", "1.0")) {
            
            Worksheet ws = wb.newWorksheet("Ganancias");
            
            // 1. Definimos las 4 columnas exactas sin SubTotal
            String[] encabezados = {"Item", "Cantidad", "Ganancia", "Total"};
            for (int col = 0; col < encabezados.length; col++) {
                ws.value(0, col, encabezados[col]);
                ws.style(0, col).bold().fillColor("2C3E50").fontColor("FFFFFF").set();
            }
            
            int rowIdx = 1;
            for (int i = 0; i < modeloVentas.getRowCount(); i++) {
                rowIdx = i + 1;
                
                String item = modeloVentas.getValueAt(i, 0) != null ? modeloVentas.getValueAt(i, 0).toString() : "";
                
                String cantStr = modeloVentas.getValueAt(i, 1) != null ? modeloVentas.getValueAt(i, 1).toString().replaceAll("[^0-9.]", "").trim() : "0";
                int cantidad = cantStr.isEmpty() ? 0 : Integer.parseInt(cantStr);
                
                double precio = 0.0;
                double costo = 0.0;
                
                // Buscar Precio y Costo en el inventario global
                if (ProductosIngresados.modeloTablaGlobal != null) {
                    for (int j = 0; j < ProductosIngresados.modeloTablaGlobal.getRowCount(); j++) {
                        Object valNombre = ProductosIngresados.modeloTablaGlobal.getValueAt(j, 1);
                        if (valNombre != null && valNombre.toString().equals(item)) {
                            String precioStr = ProductosIngresados.modeloTablaGlobal.getValueAt(j, 3) != null ? ProductosIngresados.modeloTablaGlobal.getValueAt(j, 3).toString().replaceAll("[^0-9.]", "").trim() : "0";
                            String costoStr = ProductosIngresados.modeloTablaGlobal.getValueAt(j, 4) != null ? ProductosIngresados.modeloTablaGlobal.getValueAt(j, 4).toString().replaceAll("[^0-9.]", "").trim() : "0";
                            
                            precio = precioStr.isEmpty() ? 0.0 : Double.parseDouble(precioStr);
                            costo = costoStr.isEmpty() ? 0.0 : Double.parseDouble(costoStr);
                            break;
                        }
                    }
                }
                
                // 2. Cálculos: Ganancia unitaria y Total (Cantidad * Ganancia)
                double gananciaUnitario = precio - costo;
                double totalGanancia = cantidad * gananciaUnitario;
                
                // 3. Escribir en las 4 columnas del Excel
                ws.value(rowIdx, 0, item);
                ws.value(rowIdx, 1, cantidad);
                ws.value(rowIdx, 2, gananciaUnitario);
                ws.value(rowIdx, 3, totalGanancia);
            }
            
            JOptionPane.showMessageDialog(this, "¡Reporte de Ganancias exportado con éxito!");
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error al exportar: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_jButton3ActionPerformed

