    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
       String nombre = txtproveedorNombre1.getText().trim();
    String id = txtproveedorId1.getText().trim();
    String direccion = txtproveedorDireccion.getText().trim();
    String correo = txtproveedorCorreo.getText().trim();

    if (nombre.isEmpty() || id.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Complete al menos Nombre e ID.");
        return;
    }

    String sql = "INSERT INTO proveedores (id, nombre, direccion, correo) VALUES (?, ?, ?, ?)";
    try (java.sql.Connection conn = Conexion.conectar();
         java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {
        pstmt.setString(1, id);
        pstmt.setString(2, nombre);
        pstmt.setString(3, direccion);
        pstmt.setString(4, correo);
        pstmt.executeUpdate();

        cargarProveedoresDesdeBD(); // Refresca la tabla visual
        txtproveedorNombre1.setText("");
        txtproveedorId1.setText("");
        txtproveedorDireccion.setText("");
        txtproveedorCorreo.setText("");
        javax.swing.JOptionPane.showMessageDialog(this, "¡Proveedor registrado en la base de datos!");
    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar (verifique que el ID no esté repetido): " + e.getMessage());
    }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
int fila = jTable1.getSelectedRow();
    
    if (fila >= 0) {
        // Obtenemos los valores actuales de la fila seleccionada
        String nombreActual = modeloProveedoresGlobal.getValueAt(fila, 0).toString();
        String idActual = modeloProveedoresGlobal.getValueAt(fila, 1).toString();
        String direccionActual = modeloProveedoresGlobal.getValueAt(fila, 2).toString();
        String correoActual = modeloProveedoresGlobal.getValueAt(fila, 3).toString();
        
        // Mostramos JOptionPane para editar cada campo
        String nuevoNombre = javax.swing.JOptionPane.showInputDialog(this, "Editar Nombre:", nombreActual);
        if (nuevoNombre == null) return; // Si el usuario cancela, salimos
        
        String nuevoId = javax.swing.JOptionPane.showInputDialog(this, "Editar ID:", idActual);
        if (nuevoId == null) return;
        
        String nuevaDireccion = javax.swing.JOptionPane.showInputDialog(this, "Editar Dirección:", direccionActual);
        if (nuevaDireccion == null) return;
        
        String nuevoCorreo = javax.swing.JOptionPane.showInputDialog(this, "Editar Correo:", correoActual);
        if (nuevoCorreo == null) return;
        
       
        modeloProveedoresGlobal.setValueAt(nuevoNombre, fila, 0);
        modeloProveedoresGlobal.setValueAt(nuevoId, fila, 1);
        modeloProveedoresGlobal.setValueAt(nuevaDireccion, fila, 2);
        modeloProveedoresGlobal.setValueAt(nuevoCorreo, fila, 3);
        
        javax.swing.JOptionPane.showMessageDialog(this, "Proveedor actualizado correctamente.");
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Seleccione una fila de la tabla para editar.");
    }
    
    }//GEN-LAST:event_jButton3ActionPerformed

