    public void cargarProveedoresEnComboBox() {
        // Limpiamos los elementos por defecto (Item 1, Item 2, etc.)
        txtProveedor.removeAllItems();
        
        // Recorremos las filas registradas en el modelo global de proveedores
        for (int i = 0; i < proveedor.modeloProveedoresGlobal.getRowCount(); i++) {
            // Obtenemos el nombre del proveedor de la columna 0
            Object nombreProveedor = proveedor.modeloProveedoresGlobal.getValueAt(i, 0);
            
            if (nombreProveedor != null) {
                // Lo añadimos al ComboBox de inventario
                txtProveedor.addItem(nombreProveedor.toString());
            }
        }
    }
    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed


 try {
        String nombre = txtNombre.getText().trim();
        Object proveedorObj = txtProveedor.getSelectedItem();
        String pText = txtPrecio.getText().trim();
        String cText = txtCosto.getText().trim();
        String sText = txtStock.getText().trim();

        if (nombre.isEmpty() || pText.isEmpty() || cText.isEmpty() || sText.isEmpty() || proveedorObj == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor complete todos los campos.");
            return;
        }

        double precio = Double.parseDouble(pText.replace(",", "."));
        double costo = Double.parseDouble(cText.replace(",", "."));
        int stock = Integer.parseInt(sText);
        String proveedor = proveedorObj.toString();

        String sql = "INSERT INTO productos (nombre, proveedor, precio, costo, stock) VALUES (?, ?, ?, ?, ?)";
        try (java.sql.Connection conn = Conexion.conectar();
             java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {
            
            pstmt.setString(1, nombre);
            pstmt.setString(2, proveedor);
            pstmt.setDouble(3, precio);
            pstmt.setDouble(4, costo);
            pstmt.setInt(5, stock);
            pstmt.executeUpdate();

            javax.swing.JOptionPane.showMessageDialog(this, "¡Producto registrado en la base de datos!");
            
            // Limpiar cajas de texto
            txtNombre.setText("");
            txtPrecio.setText("");
            txtCosto.setText("");
            txtStock.setText("");
        }
        
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error de formato: Precio, Costo y Stock deben ser números válidos.");
    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error en la base de datos: " + e.getMessage());
    }
    }//GEN-LAST:event_jButton1ActionPerformed

